/**
 * **나라·시대의 시작을 알아보는 규칙.** `tools/publish.mjs`가 쓰던 것을 따로 뺐다 —
 * publish.mjs는 import하면 CLI 본문이 돌아 테스트할 수 없다(`parse-year.mjs`·`text-range.mjs`·
 * `name-rules.mjs`를 뺀 것과 같은 이유).
 *
 * ── 왜 이 규칙이 필요한가 ───────────────────────────────────────────────────
 * 중요도는 위키백과 언어판 수에서 나온다(`derive.mjs`의 `score`). 그것은 **세계적 유명도**의
 * 대리값이라, 국내 연표에만 있는 사건은 구조적으로 눌린다. 그 결과 세기 레벨 한국 열 1900년대에
 * 「삼성 설립」·「남극 첫 탐험」·「엠폭스 유행」은 있는데 **「대한민국 정부 수립」이 없었다**
 * (대표 지적 2026-09-20: "국가 설립이 가장 중요한 것 아니냐").
 *
 * **새로 알아내지 않는다.** 나라·시대의 시작 연도는 이미 `curation/polities/`에 있다 — 격자가
 * 왕조 밴드를 그리는 그 값이다. 그 해에서 그 이름을 건국 동사와 가까이 쓴 줄을 찾으면 된다.
 *
 * 일본 열의 정치체는 나라가 아니라 **시대**다(헤이안·에도·헤이세이). 그래서 이 표시는 일본에서
 * "국가 설립"이 아니라 "그 열의 시대가 바뀌는 지점"을 뜻하고, 그쪽이 같은 자리의 사실이다.
 *
 * 의존성 0.
 */

/**
 * **시작을 분명히 말하는 말.**
 *
 * 「국호」가 있는 이유는 **중국 왕조가 건국을 국호 제정으로 적기** 때문이다(「국호를 「대명」이라 함」).
 * 「독립 선언」·「제헌」이 있는 이유는 **미국이 건국을 그렇게 적기** 때문이다 — 1776년 줄의 이름은
 * 「독립 선언문 공포」이고 「미국」도 「건국」도 없다. 나라마다 자기 시작을 부르는 말이 다르고,
 * 그 말을 표에 넣지 않으면 그 나라만 조용히 빠진다(2026-09-21 실측: 미국 열이 그랬다).
 */
export const FOUND_VERB_STRONG =
  /건국|개국|수립|성립|건립|창건|국호|독립\s*선언|제헌|(시대|왕조)\s*(가|를)?\s*(시작|개막)/;

/**
 * 위에 **「즉위」를 더한 것.** 즉위는 시작을 뜻할 때도 있고(「메이지 천황 즉위」가 메이지 시대의
 * 유일한 표식이다) 아닐 때도 있다(「항우 서초패왕 즉위」는 한나라의 시작이 아니다 — 한나라는
 * -202년 유방의 즉위로 선다). 그래서 **약한 말**로 따로 둔다: 정치체 이름을 곁에 둔 줄에서는
 * 받아들이고, 이름만 보고 고르는 자리에서는 받지 않는다(`FOUND_VERB_STRONG` 쪽을 쓴다).
 */
export const FOUND_VERB = new RegExp(`${FOUND_VERB_STRONG.source}|즉위`);

/**
 * 이 이름이 시작을 얼마나 분명히 말하는가. **0 분명 · 1 약함 · 2 말하지 않음.**
 *
 * 한 정치체의 시작 해에 여러 줄이 걸릴 때 이것이 첫 가늠자다. 1776년 미국 열에는 「독립 선언문
 * 공포」(0)와 「스태튼아일랜드 평화 회의」(2)가 함께 걸렸다 — 뒤엣것은 본문에 「미국의 독립
 * 선언」이라는 구절이 있어 `foundsNear`의 18자 창에 든 것이지, 그 줄이 건국인 것이 아니다.
 */
export const foundStrength = (name) => {
  const n = String(name ?? "");
  return FOUND_VERB_STRONG.test(n) ? 0 : FOUND_VERB.test(n) ? 1 : 2;
};

/**
 * 밴드 이름에서 핵만 남긴다. 「삼국 시대」 → 「삼국」, 「진 (위진)」 → 「진」.
 * 꼬리를 떼지 않으면 본문의 「삼국」과 글자가 맞지 않는다.
 */
export const politiyCore = (name) =>
  String(name ?? "")
    .replace(/\s*\(.*\)$/, "")
    .replace(/\s*시대$/, "")
    .trim();

/**
 * 이 줄이 그 정치체의 시작을 말하는가. **두 꼴**을 받는다.
 *
 *   1) 이름 바로 뒤 18자 안에 건국 동사 — 「고려 건국」 · 「대한민국 정부 수립」
 *      18자로 자르는 이유: 문장 저 끝의 동사가 걸리면 「중화인민공화국 **성립** 이래 최대의
 *      탄광 사고」가 건국으로 읽힌다. 실측에서 실제로 걸리던 줄이다.
 *
 *   2) 국호를 말하며 국명을 인용한 꼴 — 「국호를 「대명」이라 함」 · 「국호를 「대원」으로 고치니」
 *      중국 왕조는 자기 이름을 「명나라」가 아니라 「대명」으로 적는다. 1)만으로는 원·명의 건국이
 *      통째로 빠졌다(실측: 1368년 세기 레벨에 「광시 정복」은 있고 명나라 건국은 없었다).
 *      이 꼴이 더 잡는 것은 송·원·명·청 **4건뿐이고 오탐은 0**이었다.
 *
 * @param {string} text 그 줄의 이름·번역·원문을 이어 붙인 것
 * @param {string} core `politiyCore()`를 거친 정치체 이름
 */
export function foundsNear(text, core) {
  const t = String(text ?? "");
  const c = String(core ?? "");
  if (!c) return false;
  for (let i = t.indexOf(c); i >= 0; i = t.indexOf(c, i + 1)) {
    if (FOUND_VERB.test(t.slice(i, i + c.length + 18))) return true;
  }
  const short = c.replace(/나라$|제국$/, "");
  return short.length > 0 && /국호/.test(t) && new RegExp(`[「『"]대?${short}[」』"]`).test(t);
}
