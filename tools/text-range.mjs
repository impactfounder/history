/**
 * 연표 한 줄의 **본문에서 기간(끝 연도)을 읽는다.** `tools/derive.mjs`의 `endYearOf`가 쓰던
 * 규칙을 따로 뺀 것이다 — derive.mjs는 import하면 CLI 본문이 돌아 테스트할 수 없었다
 * (`parse-year.mjs`를 뺀 것과 같은 이유).
 *
 * ── 이 함수가 틀리면 화면에 **없는 기간 막대**가 그려진다 ──────────────────
 * 원래 규칙은 "본문 어디든 연도 범위가 있고 그 시작이 이 줄의 해와 ±1이면 기간"이었다.
 * 대부분 맞는다 — 연표 줄은 보통 `Song-Xia War (1040–1044): …`처럼 **사건 이름 바로 뒤에**
 * 자기 기간을 적기 때문이다. 실측(2026-09-20) 56건 중 52건이 그런 경우다.
 *
 * 틀리는 나머지 4건은 두 꼴이었다:
 *
 *   1) 서명 안의 범위 — `《1956-1967年科学技术发展远景规划纲要》正式出台`
 *      「1956-1967년 계획」이라는 **문서 이름**이지 사건의 기간이 아니다.
 *
 *   2) 뒷절의 범위 — `1941年：皖南事变。太平洋戰爭（1941-1945）起。`
 *      이 줄의 사건은 환남사변인데, 범위는 뒤 문장의 **태평양 전쟁** 것이다.
 *      환남사변이 1945년까지 이어지는 막대가 된다.
 *
 * 라틴 마침표(`.`)는 종결로 보지 않는다 — `Jan.`·`U.S.`·`c.`가 걸려 멀쩡한 기간을 죽인다.
 * 실측에서 잘못 잡힌 뒷절 셋은 전부 CJK 종결부호였다.
 *
 * 의존성 0.
 */

/** 연도 범위 표기. `1592–1598` · `1592-1598` · `1592년부터 1598` */
export const RANGE_RE = /(?<![\d])(\d{3,4})\s*(?:[–—~-]|년부터\s*)(\d{3,4})(?![\d])/;

/** 서명 — 닫히지 않은 여는 기호가 범위 앞에 있으면 그 안이다. */
const OPEN_TITLE = /[《「『〈][^》」』〉]*$/;
/** CJK 문장 종결. 이 뒤의 범위는 다른 절의 것이다. */
const CJK_END = /[。．！？]/;

/**
 * 본문이 말하는 끝 연도. 없으면 `null`.
 *
 * @param {string} text 연표 한 줄 원문
 * @param {number} year 그 줄의 연도
 * @returns {number | null} 끝 연도
 */
export function textEndYear(text, year) {
  const m = RANGE_RE.exec(String(text ?? ""));
  if (!m) return null;
  const head = String(text).slice(0, m.index);
  if (OPEN_TITLE.test(head)) return null; // 문서 이름 안
  if (CJK_END.test(head)) return null; // 앞 문장이 끝났다 — 이 줄의 사건이 아니다
  const a = Number(m[1]), b = Number(m[2]);
  // 시작이 이 줄의 해와 맞고(±1), 100년을 넘지 않을 때만. 왕조 길이가 사건에 붙는 것을 막는다
  if (b > a && b - a <= 100 && Math.abs(a - year) <= 1) return b;
  return null;
}
