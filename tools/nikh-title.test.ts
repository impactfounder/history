import { describe, expect, it } from "vitest";

import { titleOf } from "./nikh-title.mjs";

/**
 * 국사편찬위 줄의 제목. 겹꺾쇠(≪≫)는 출전에도, 문장 속 책 이름에도 쓰인다 — 첫 겹꺾쇠에서 무조건 자르던
 * 처음 판은 뒤쪽 때문에 칩에 「삼군부(三軍府)에서」 같은 반쪽 문장을 띄웠다(2026-09-26, 61줄).
 * 예문은 모두 실제 원문(curation/raw/nikh) 꼴이다.
 */
describe("titleOf — 국편 제목", () => {
  it("문장 속 책 이름에서 자르지 않는다", () => {
    expect(titleOf("(태조 4년) 삼군부(三軍府)에서 ≪수수도(蒐狩圖)≫와 ≪진도(陣圖)≫를 간행함.≪조선왕조실록≫"))
      .toBe("삼군부(三軍府)에서 ≪수수도(蒐狩圖)≫와 ≪진도(陣圖)≫를 간행함.");
  });

  it("출전 앞의 저자 조각을 떼어 낸다", () => {
    expect(titleOf("일본군 제1군이 절영도(絶影島)에 상륙. 임진왜란 시작.이이화, ≪한국사 이야기≫ 11, 2000"))
      .toBe("일본군 제1군이 절영도(絶影島)에 상륙. 임진왜란 시작.");
  });

  it("이미 문장으로 끝난 줄은 출전만 뗀다 — 출전 속 「권8 가묘도.」를 문장으로 잇지 않는다", () => {
    expect(titleOf("사대부의 가묘 제도를 정하고 참람한 것을 금하도록 함.≪태종실록≫ 권8 가묘도."))
      .toBe("사대부의 가묘 제도를 정하고 참람한 것을 금하도록 함.");
  });

  it("이을 조각에 쪽수·연도·＜＞가 섞이면 출전을 삼킨 것이므로 잇지 않는다", () => {
    expect(titleOf("경상도 우병영에서 ≪병학지남(兵學指南)≫을 중간함도수희, 1970 ＜병학지남언해에 대하여＞ ≪어문연구≫6, 6쪽."))
      .toBe("경상도 우병영에서");
  });

  it("마침표가 없는 원문 — 책 이름 뒤 다음 출전 괄호 직전까지 잇는다(2026-09-27)", () => {
    expect(titleOf("삼강군(三江郡)에서 ≪총통식(銃筒式)≫ 간행≪신기비결≫")).toBe("삼강군(三江郡)에서 ≪총통식(銃筒式)≫ 간행");
    expect(titleOf("정약용(丁若鏞)이 민간방위체제에 관한 병서인 ≪민보의(民堡議)≫를 저술함 ≪고병서해제≫, 육군본부, 1979, 82쪽민보의"))
      .toBe("정약용(丁若鏞)이 민간방위체제에 관한 병서인 ≪민보의(民堡議)≫를 저술함");
  });

  it("괄호 앞이 끝난 문장이면 첫 괄호는 출전이다 — 잇지 않는다", () => {
    expect(titleOf("여진족의 간청으로 9성을 여진족에게 돌려줌≪고려사절요≫권7, 예종 4년 7월")).toBe("여진족의 간청으로 9성을 여진족에게 돌려줌");
  });

  it("본문의 연도는 출전이 아니다 — 쉼표 뒤 연도·쪽수·＜＞만 막는다", () => {
    expect(titleOf("1455년 작은 활자로 간행된 ≪소자진서(小字陣書)≫와 1459년 큰 활자로 간행된 ≪대자진서(大字陣書)≫를 합하여 한 책으로 합본함.≪조선왕조실록≫"))
      .toBe("1455년 작은 활자로 간행된 ≪소자진서(小字陣書)≫와 1459년 큰 활자로 간행된 ≪대자진서(大字陣書)≫를 합하여 한 책으로 합본함.");
  });

  it("겹꺾쇠가 없으면 왕대 표기만 뗀다", () => {
    expect(titleOf("(세종 15년 6월) 판중추부사 하경복이 진서를 올림.")).toBe("판중추부사 하경복이 진서를 올림.");
  });
});
