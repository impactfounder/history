import { describe, expect, it } from "vitest";

import { FOUND_VERB, FOUND_VERB_STRONG, foundStrength, foundsNear, politiyCore } from "./founding.mjs";

/**
 * 나라·시대의 시작을 알아보는 규칙. 틀리면 **첫 화면에 엉뚱한 것이 맨 앞에 선다** —
 * 이 표시는 중요도를 5로 올리고 같은 중요도 안에서 언어판 수보다 먼저 정렬되므로, 오탐 한 건이
 * 그 세기의 대표 자리를 가져간다.
 *
 * 아래 문자열은 전부 실제 발행 데이터에서 왔다(2026-09-20 실측).
 */
describe("건국을 말하는 줄", () => {
  it.each([
    ["8월 15일 대한민국 정부 수립", "대한민국"],
    ["고려의 시조 태조 왕건이 철원에서 고려 건국", "고려"],
    ["조선 건국", "조선"],
    ["대한제국 고종이 제위에 등극하고, 대한제국을 수립해 연호를 광무로 고침", "대한제국"],
    ["9월 9일 조선민주주의인민공화국 정부 수립", "조선민주주의인민공화국"],
    ["월1일, 중화인민공화국 개국대전이 열려 \"중화인민공화국 중앙인민정부\"가 수립되고", "중화인민공화국"],
    ["중화민국 남경 임시정부가 성립, 손문이 임시대총통에 취임", "중화민국"],
    ["간무 천황이 도읍을 헤이안쿄로 옮기면서 헤이안 시대가 시작된다", "헤이안"],
  ])("%s", (text, core) => {
    expect(foundsNear(text, core)).toBe(true);
  });

  /**
   * 중국 왕조는 자기 이름을 「명나라」가 아니라 「대명」으로 적는다. 이 꼴이 없으면 원·명의
   * 건국이 통째로 빠진다 — 실측에서 1368년 세기 레벨에 「광시 정복」은 있고 명나라 건국은
   * 없었다.
   */
  it.each([
    ["홍무제가 남경에서 황제를 칭하고, 국호를 「대명」이라 함.", "명나라"],
    ["몽골이 국호를 「대원」으로 고치니, 몽골어로는 「대원대몽골국」이라 하며", "원나라"],
    ["대금이 국호를 「대청」으로 고치고, 황태극이 황제를 칭하여, 청나라가 건립되다.", "청나라"],
  ])("국호 꼴 — %s", (text, core) => {
    expect(foundsNear(text, core)).toBe(true);
  });
});

describe("건국이 아닌 줄 — 이름만 스쳐 지나간다", () => {
  /**
   * **18자 창이 막는 것과 못 막는 것.** 창은 이름에서 먼 동사를 끊는다 — 아래 첫 줄이 그 경우다.
   *
   * 그러나 「중화인민공화국 **성립** 이래 최대의 사고」처럼 이름과 동사가 **붙어 있는** 줄은
   * 글자만으로 가려낼 수 없다. 이 테스트를 쓰면서 그 사실을 확인했다(막는다고 적었다가 빨개졌다).
   *
   * 그것을 막는 것은 규칙이 아니라 **선택**이다 — `publish.mjs`는 정치체마다 후보 중 **한 줄만**
   * 고르고, 그 해에 진짜 건국 행이 있으면 정렬에서 그것이 이긴다. 1949년에 개국대전 줄이 있으므로
   * 탄광 사고는 대표가 되지 않는다. 오탐이 실제로 대표가 되는 경우는 **그 해에 진짜가 아예 없을
   * 때뿐**이고, 그때는 그 정치체에 표시가 없는 편이 낫다는 판단이 따로 필요하다.
   */
  it("이름에서 먼 동사는 끊는다", () => {
    expect(
      foundsNear("27일, 허난 이뤄 탄광 사고로 174명이 사망하고 39명이 부상당했다. 중화인민공화국 최대 규모였으며 이후 안전 규정이 수립되었다", "중화인민공화국"),
    ).toBe(false);
  });

  it("붙어 있는 동사는 글자로 못 가려낸다 — 방어는 정치체마다 한 줄만 고르는 쪽이다", () => {
    expect(
      foundsNear("27일, 허난 이뤄 탄광 사고로 174명이 사망하여, 중화인민공화국 성립 이래 최대의 사고가 되었다", "중화인민공화국"),
    ).toBe(true);
  });

  it.each([
    ["진나라가 연나라, 월나라, 대나라를 멸망시켰다.", "진나라"],
    ["정형 전투: 한나라 군대가 정형관에서 조나라 군대에게 결정적인 패배를 안겼다", "한나라"],
    ["11월. 대한민국 국회가 국가보안법을 통과시킨다.", "대한민국"],
    ["1월 — 병자호란: 조선의 인조가 숭덕제의 청나라를 중국의 정통 왕조로 인정했다", "청나라"],
  ])("%s", (text, core) => {
    expect(foundsNear(text, core)).toBe(false);
  });

  it("이름이 아예 없으면 건국이 아니다", () => {
    expect(foundsNear("을지문덕이 살수에서 수군을 대파함", "대한민국")).toBe(false);
  });

  it("빈 입력에 던지지 않는다", () => {
    expect(foundsNear("", "조선")).toBe(false);
    expect(foundsNear("조선 건국", "")).toBe(false);
    expect(foundsNear(undefined as unknown as string, undefined as unknown as string)).toBe(false);
  });
});

describe("밴드 이름의 꼬리를 뗀다", () => {
  it.each([
    ["삼국 시대", "삼국"],
    ["진 (위진)", "진"],
    ["삼국 시대 (중국)", "삼국"],
    ["대한민국", "대한민국"],
    ["오대 십국 시대", "오대 십국"],
  ])("%s → %s", (name, core) => {
    expect(politiyCore(name)).toBe(core);
  });

  it("꼬리를 떼지 않으면 본문과 글자가 맞지 않는다", () => {
    expect(foundsNear("아스카 시대가 시작되고, 왕도가 아스카로 옮겨진다", politiyCore("아스카 시대"))).toBe(true);
  });
});

describe("건국 동사 표", () => {
  it("국호가 들어 있다 — 중국 왕조는 건국을 국호 제정으로 적는다", () => {
    expect(FOUND_VERB.test("국호")).toBe(true);
  });

  it("전투·조약 같은 말은 들어 있지 않다", () => {
    for (const w of ["전투", "조약", "사고", "멸망", "함락", "정복"]) {
      expect(FOUND_VERB.test(w), w).toBe(false);
    }
  });
});

describe("시작을 얼마나 분명히 말하는가", () => {
  it.each([
    ["독립 선언문 공포", 0],
    ["대한민국 정부 수립", 0],
    ["헤이안 시대 시작", 0],
    ["메이지 천황 즉위", 1],
    ["스태튼아일랜드 평화 회의", 2],
    ["롱아일랜드 전투", 2],
    [null, 2],
  ])("%s → %d", (name, want) => {
    expect(foundStrength(name as string | null)).toBe(want);
  });

  /*
    **「즉위」는 약한 말이다.** 정치체 이름을 곁에 둔 줄에서는 받아야 한다 — 메이지 시대의
    유일한 표식이 「메이지 천황 즉위」다. 그러나 이름만 보고 고르는 자리에서 받으면 -205년
    한나라 칸에 「항우 서초패왕 즉위」가 선다. 한나라는 -202년 유방의 즉위로 서므로 그것은
    그 나라의 시작이 아니다.
  */
  it("즉위는 약한 표에만 있다", () => {
    expect(FOUND_VERB.test("즉위")).toBe(true);
    expect(FOUND_VERB_STRONG.test("즉위")).toBe(false);
  });

  it("분명한 말은 두 표에 다 있다", () => {
    for (const w of ["건국", "수립", "국호", "독립 선언", "제헌"]) {
      expect(FOUND_VERB_STRONG.test(w), w).toBe(true);
      expect(FOUND_VERB.test(w), w).toBe(true);
    }
  });

  /*
    미국 열이 걸렸던 자리. 1776년 줄 이름에 「미국」이 없어 `foundsNear`로는 못 잡고, 대신
    본문에 「미국의 독립 선언」이 있는 9월 11일 평화 회의가 걸렸다. 이름만 보면 갈린다.
  */
  it("본문이 아니라 이름을 보면 미국의 1776이 갈린다", () => {
    expect(foundsNear("스태튼아일랜드 평화 회의. 영국 당국과 대륙회의 대표들이 미국의 독립 선언 철회를 논의함", "미국")).toBe(true);
    expect(foundStrength("스태튼아일랜드 평화 회의")).toBe(2);
    expect(foundStrength("독립 선언문 공포")).toBe(0);
  });
});
